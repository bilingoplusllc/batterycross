def px_form(alias):
    """Историческая форма PX625 при фирменной EPX625.

    Приставка E — марка Energizer поверх серии PX, и на старых приборах, в
    руководствах и в поиске живёт именно голая форма.
    """
    a = (alias or "").upper()
    return a[1:] if re.match(r"^EPX\d", a) else None


def slug(cell):
    s = re.sub(r"[^a-z0-9]+", "-", cell["code"].lower()).strip("-")
    return re.sub(r"-+", "-", s)


def shell_slug(s):
    """Адрес страницы оболочки. ОДНА функция на сайт: адрес, собранный в двух
    местах по-разному, однажды разойдётся."""
    if not s:
        return None
    body = "-".join(("%.1f" % v).rstrip("0").rstrip(".").replace(".", "-")
                    for v in s[1:])
    return "%s-%s-mm" % (shell_form(s), body)


def shell_form(s):
    """Монета, цилиндр или коробка — ОДНО правило, то же, что у is_coin.

    Раньше всё круглое звалось монетой, и четыре адреса из одиннадцати врали
    прямо в строке браузера: /shell/coin-14-5-50-5-mm/ — это пальчиковый
    цилиндр 14,5 x 50,5 мм, никакая не монета. Адрес виден человеку и уходит
    в выдачу; менять его после публикации дорого, до публикации — бесплатно.
    """
    if s[0] != "round":
        return "box"
    return "coin" if s[2] < s[1] else "cylinder"


