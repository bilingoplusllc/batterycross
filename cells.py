NOT_VALUES = ("", "N/A", "None", "[]", "Choose a Replacement", "nan")


def _s(row, key):
    v = str(row.get(key) or "").strip()
    return "" if v in NOT_VALUES else v


def _f(row, key):
    v = _s(row, key)
    if not v:
        return None
    m = re.search(r"-?\d+(?:\.\d+)?", v.replace(",", ""))
    return float(m.group(0)) if m else None


def iec_all(row):
    """ВСЕ обозначения МЭК изделия. Поле может нести их несколько.

    «6LF22 or 6LR61» — это одна щелочная «Крона» под двумя равноправными
    обозначениями стандарта, а не код с пробелом. Собранное как один код, оно
    завело сущность «6LF22 OR 6LR61» и оставило настоящий 6LR61 без единого
    действующего изделия — то есть объявило снятой с производства обычную
    девятивольтовую батарейку из дымового датчика, а замену предложило
    угольно-цинковую. Тот же класс, что и «status изделия, напечатанный как
    судьба обозначения».
    """
    raw = re.sub(r"^IEC[\s:-]*", "", _s(row, "battery-iec")).strip().upper()
    if not raw:
        return []
    out = []
    for x in re.split(r"\s+OR\s+", raw):
        x = x.strip()
        if x and x not in out:
            out.append(x)
    return out


def iec_of(row):
    a = iec_all(row)
    return a[0] if a else ""


def ansi_of(row):
    return re.sub(r"^ANSI[\s:/-]*(?:NEDA[\s:/-]*)?", "",
                  _s(row, "battery-ansineda")).strip().upper()


def load():
    return json.load(io.open(RAW, encoding="utf-8"))


# ------------------------------------------------------------ обозначение МЭК

# Четырёхзначный код МЭК кодирует габарит: две первые цифры — диаметр в целых
# миллиметрах, две последние — высота в десятых. CR2032 = 20 мм на 3,2 мм.
IEC_4 = re.compile(r"^([A-Z]{1,2})(\d{2})(\d{2})$")

CHEM_LETTER = {
    "C": ("lithium manganese dioxide", 3.0),
    "B": ("lithium carbon monofluoride", 3.0),
    "L": ("alkaline manganese dioxide", 1.5),
    "S": ("silver oxide", 1.55),
    "P": ("zinc air", 1.4),
    "M": ("mercuric oxide", 1.35),
}


def decode_iec(code):
    """Что говорит САМО обозначение. Второй, независимый источник размера.

    Возвращает (диаметр, высота, буква химии) или None, если код не из
    четырёхзначных. Диаметр в коде — целые миллиметры, поэтому 12,5 мм
    записывается как 12: код округляет ВНИЗ, и расхождение на полмиллиметра
    здесь не ошибка данных, а свойство стандарта. Мы это и говорим.
    """
    m = IEC_4.match((code or "").strip().upper())
    if not m:
        return None
    letters, d, h = m.group(1), int(m.group(2)), int(m.group(3))
    if not (4 <= d <= 40 and 1 <= h <= 99):
        return None
    return (float(d), h / 10.0, letters[0])


def code_check(cell):
    """Сверка кода с заявленным размером. Расхождение — находка, а не сбой.

    Возвращает None, если сверять нечего; иначе словарь с обоими числами и
    словесным итогом: код и изготовитель сошлись, код округлил вниз, или они
    расходятся сверх округления.
    """
    dec = decode_iec(cell.get("code"))
    if not dec or cell.get("diameter") is None or cell.get("height") is None:
        return None
    d_code, h_code, _letter = dec
    d_real, h_real = cell["diameter"], cell["height"]
    dd, dh = d_real - d_code, h_real - h_code
    if abs(dd) < 0.05 and abs(dh) < 0.05:
        verdict = "exact"
    elif 0 <= dd < 1.0 and abs(dh) < 0.05:
        verdict = "rounded"          # стандарт округляет диаметр вниз
    else:
        verdict = "differs"
    return {"d_code": d_code, "h_code": h_code, "d_real": d_real,
            "h_real": h_real, "dd": dd, "dh": dh, "verdict": verdict}


