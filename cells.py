def facts(cell, cells, ranks):
    """Вычисленные величины страницы. Именно они проходят гейт достаточности.

    Каждая — результат расчёта, а не строка из источника: отношение, сверка,
    место в ряду или классификация. Переписанное напряжение фактом не считается.
    """
    out = []
    if cell.get("code_check"):
        out.append("code:%s:%s" % (cell["code"], cell["code_check"]["verdict"]))
    fam = family(cell, cells)
    if fam:
        out.append("shell:%s:%d" % (cell["code"], len(fam)))
    reps = replacements(cell, cells)
    if reps:
        out.append("repl:%s:%d" % (cell["code"], len(reps)))
        if reps[0]["volt"]:
            out.append("volt:%s:%s" % (cell["code"], reps[0]["volt"]["class"]))
    d = density_mwh_cc(cell)
    if d:
        out.append("dens:%s:%.1f" % (cell["code"], d))
    e = energy_mwh(cell)
    if e:
        out.append("energy:%s:%.0f" % (cell["code"], e))
    r = ranks.get(cell["code"])
    if r:
        out.append("rank:%s:%d/%d" % (cell["code"], r[0], r[1]))
    return out


