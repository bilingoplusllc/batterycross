def shell(cell):
    """Оболочка — то, что решает, влезет ли элемент в отсек.

    Форм две, и мерятся они по-разному: круглая задаётся диаметром и высотой,
    призматическая — длиной, шириной и высотой. Первая версия знала только
    круглую и молча выбрасывала «Крону» и все батареи-сборки: шестьдесят
    четыре элемента оставались без ответа на главный вопрос сайта.
    """
    h = cell.get("height")
    if h is None:
        return None
    d = cell.get("diameter")
    if d is not None:
        return ("round", round(d, 1), round(h, 1))
    lg, wd = cell.get("length"), cell.get("width")
    if lg is not None and wd is not None:
        return ("box", round(lg, 1), round(wd, 1), round(h, 1))
    return None


def is_coin(cell):
    """Монета или цилиндр. Различие настоящее и вычисляемое: у монеты высота
    меньше диаметра, у цилиндра — больше, и это разные классы предметов.

    Без него в «лестницу толщин» часового элемента 7,9 x 2,6 мм попадал
    цилиндр 7,9 x 39,8 мм: тот же диаметр, но никакой это не сосед.
    """
    d, h = cell.get("diameter"), cell.get("height")
    if d is None or h is None:
        return None
    return h < d


def shell_label(s):
    """Оболочка словами. ОДНА функция на сайт: величина, названная в двух
    местах по-разному, однажды разойдётся публично."""
    if not s:
        return None
    if s[0] == "round":
        return "%s x %s mm" % (_mm(s[1]), _mm(s[2]))
    return "%s x %s x %s mm" % (_mm(s[1]), _mm(s[2]), _mm(s[3]))


def _mm(v):
    return ("%.1f" % v).rstrip("0").rstrip(".")


def fit_gap(a_mm, b_mm):
    """Расстояние между двумя мерами В ТОМ ВИДЕ, В КАКОМ ОНО НАПЕЧАТАНО.
    ОДНА функция на сайт, и всё, что решает вердикт посадки, считает по ней.

    Сайт печатает каждую меру десятой долей миллиметра (_mm), и читатель
    вычитает ровно напечатанное. Двоичный хвост разности этого не знает:
    1.6 - 1.3 это 0.30000000000000004, то есть «больше допуска 0,3» — и пара
    346 / SR716W, у которой на обеих страницах напечатаны 1.3 и 1.6, получала
    «не drop-in» по правилу, которое на напечатанных цифрах даёт drop-in.
    Совпадение с сырыми данными там было СЛУЧАЙНЫМ.

    Это ровно та болезнь, которую pair_figure вылечил для напряжения:
    вердикт обязан следовать за напечатанной цифрой, а не за её двоичным
    остатком. Округляются ОБА операнда — функцию зовут и от сырого поля
    записи, и от уже округлённой меры shell(), и ответ обязан быть один.
    """
    return round(round(b_mm, 1) - round(a_mm, 1), 1)


def fits(a, b):
    """Встанет ли b туда, где стоял a. Пять РАЗНЫХ ответов, а не «да/нет».

    Величина, названная одним словом, теряет то, ради чего человек пришёл:
    «подойдёт» для отсека с пружиной и для отсека с жёстким контактом — разные
    ответы, и он должен видеть, чем именно отличается.

    Все разности берутся у fit_gap, то есть считаются по НАПЕЧАТАННЫМ
    десятым: вердикт, который читатель не может проверить вычитанием двух
    цифр со страницы, — это вердикт про другие числа.
    """
    sa, sb = shell(a), shell(b)
    if not sa or not sb or sa[0] != sb[0]:
        return None
    if sa[0] == "round":
        dd, dh = fit_gap(sa[1], sb[1]), fit_gap(sa[2], sb[2])
    else:
        # У призматической две поперечных меры, и обе обязаны совпасть.
        d1 = fit_gap(sa[1], sb[1])
        d2 = fit_gap(sa[2], sb[2])
        dh = fit_gap(sa[3], sb[3])
        if abs(d1) > FIT_MM or abs(d2) > FIT_MM:
            return "wider" if (d1 > 0 or d2 > 0) else "narrower"
        dd = 0.0
    if abs(dd) > FIT_MM:
        return "wider" if dd > 0 else "narrower"
    if abs(dh) <= FIT_MM:
        return "drop-in"
    return "taller" if dh > 0 else "shorter"


FIT_ORDER = {"drop-in": 0, "shorter": 1, "taller": 2, "narrower": 3,
             "wider": 4, None: 5}


def signed_ratio(base_volts, other_volts):
    """ЕДИНСТВЕННОЕ место на сайте, где считается отношение напряжений.

    База — ВСЕГДА тот элемент, который человек держит в руках; знак говорит,
    куда уедет напряжение, если поставить вместо него другой. Направление
    здесь СПРАШИВАЕТСЯ У ДАННЫХ и возвращается знаком: на этой ферме уже
    выходило «в 0,2 раза дольше» на девяти страницах, где на деле было вшестеро
    меньше, потому что направление подразумевалось словом в шаблоне.
    """
    if not base_volts or not other_volts:
        return None
    return (other_volts - base_volts) / base_volts


def signed_pct(ratio):
    """Печатаемая величина. Всё, что ниже, считает КЛАСС и ГЕОМЕТРИЮ по ней —
    именно поэтому напечатанный процент и метка рядом с ним не могут
    разойтись."""
    if ratio is None:
        return None
    return round(ratio * 100.0, 1)


def pair_pct(pct):
    """Напечатанный процент — В МЕРУ ПАРЫ. Одно отношение — одно число.

    Печатается процент ОТ ЭТОГО элемента: человек держит в руках именно его,
    и «на четверть выше, чем ждёт отсек» — это про его отсек. Но пара 1,2 и
    1,5 В — ОДНО физическое отношение, а от 1,5 оно даёт -20%, от 1,2 даёт
    +25%, и по границе 20% одна страница печатала «работать будет, покажет не
    то», а вторая — «другой класс, не замена». Про один и тот же щелочной
    элемент в отсеке аккумулятора, то есть про самую частую замену на свете.

    Мера пары — разрыв, отнесённый к БОЛЬШЕМУ из двух номиналов: 0,3 В между
    1,2 и 1,5 это 20% от 1,5 с любой стороны. Знак остаётся направлением
    ЗАМЕНЫ, потому что подставить ниже и подставить выше — разные поступки,
    и слова класса у них разные; величина мисматча при этом одна.
    """
    if pct is None:
        return None
    return pct / (1.0 + pct / 100.0) if pct > 0 else pct


def pair_figure(ratio):
    """Мера пары В ТОМ ВИДЕ, В КАКОМ ОНА ПЕЧАТАЕТСЯ. Одно число на пару.

    Округление здесь не косметика, а место, где решается граница класса.
    signed_pct уже округляет ПЕЧАТАЕМЫЙ процент стороны, но деление на меру
    пары возвращает двоичный хвост: 20.0000000004 читается как «больше 20»
    и уводит пару за границу класса, тогда как на странице напечатано ровно
    «20.0%». Класс обязан следовать за напечатанной цифрой, а не за её
    двоичным остатком, — и цифра эта та же самая, что печатает pct_num:
    десятая доля до сотни процентов, целое дальше.
    """
    p = signed_pct(ratio)
    if p is None:
        return None
    m = abs(pair_pct(p))
    return float(round(m)) if m >= 100.0 else round(m, 1)


def consequence_class(ratio):
    """ЕДИНСТВЕННОЕ место, где отношение превращается в последствие.

    Границы читаются по НАПЕЧАТАННОЙ мере пары (pair_figure): иначе одна и
    та же пара получает два разных класса, смотря с чьей страницы на неё
    смотрят, а на самой границе — ещё и смотря на двоичный хвост деления.
    Классы отвечают на разные вопросы, а не на один с разной силой: «то же
    рабочее напряжение», «прибор с калибровкой заметит», «показания
    уплывут», «другой класс напряжения».
    """
    if ratio is None:
        return None
    m = pair_figure(ratio)
    if m <= V_SAME_PCT:
        return "same"
    if m <= V_MINOR_PCT:
        return "minor"
    if m <= V_SERIOUS_PCT:
        return "calibration"
    return "wrong"


def class_edge(sign):
    """Граница класса «работать будет» В ТЕХ ЖЕ КООРДИНАТАХ, что и печатаемый
    процент, то есть от ЭТОГО элемента. Вниз это -20%, вверх +25%: тот же
    разрыв в 20% большего номинала, отсчитанный от меньшего числа.

    ОДНА функция на текст оси, на зону дорожки и на гейт. Пока края зоны
    набирались как +-V_SERIOUS_PCT, дорожка обещала симметрию, которой у
    меры нет, и штрих +25% стоял вне зоны с меткой «reads off».
    """
    s = V_SERIOUS_PCT / 100.0
    return s / (1.0 - s) if sign > 0 else -s


def gap_pct(a_volts, b_volts):
    """НАСКОЛЬКО ВРОЗЬ два номинала, без направления. Одно число на пару.

    Слово «apart» симметрично, и число рядом с ним обязано быть симметричным
    тоже: витрина оболочки печатала «1.2 V ... 1.5 V, 25.0% apart», считая от
    меньшего, а страницы тех же двух элементов решали класс по 20% — по той
    же паре. Это та же мера, по которой считается класс.
    """
    return pair_figure(signed_ratio(a_volts, b_volts))


def scale_position(ratio):
    """Место штриха на дорожке, 0..100. Строго монотонно по signed_ratio.

    Ядро линейно до +-20% (та самая граница класса) и занимает средние 60%
    дорожки; дальше — логарифм до конца оси. Поэтому 3% и 700% не могут
    нарисоваться одинаково, а положение штриха значит одно и то же на любой
    странице сайта.
    """
    if ratio is None:
        return None
    p = signed_pct(ratio)
    m = abs(p)
    # Ядро кончается ТАМ ЖЕ, ГДЕ КЛАСС, а край класса с этой стороны знает
    # class_edge: вверх это +25%, вниз -20%. Пока здесь стояло V_SERIOUS_PCT
    # на обе стороны, зона дорожки резала класс пополам.
    edge = abs(class_edge(1 if p > 0 else -1)) * 100.0
    if m <= edge:
        x = V_AXIS_CORE_HALF * m / edge
    else:
        end = V_AXIS_HIGH_PCT if p > 0 else -V_AXIS_LOW_PCT
        if m >= end:
            x = 50.0
        else:
            x = V_AXIS_CORE_HALF + (50.0 - V_AXIS_CORE_HALF) * (
                math.log10(m / edge) / math.log10(end / edge))
    return round(50.0 + (x if p > 0 else -x), 1)


# Химия, чьё последствие столбец напряжения НЕ ВЫРАЖАЕТ. Ключ — химия
# кандидата; значение проверяется отдельно от процентов, потому что цена
# цинк-воздушного элемента в часах — не 6,9% вольта, а то, что он начинает
# разряжаться, как только снята наклейка, и задыхается в закрытом отсеке.
CHEM_CAVEAT_KEYS = ("rechargeable", "air", "carbon")


def chemistry_caveat(base, other):
    """Последствие ЗАМЕНЫ, которого не видно в процентах. Отдельный вердикт с
    отдельным именем: посадка, электрика и химия не сливаются."""
    a, b = CHEM_CANON.get(base.get("chemistry") or ""), \
        CHEM_CANON.get(other.get("chemistry") or "")
    if not b or a == b:
        return None
    if b == "nickel-metal hydride":
        return "rechargeable"
    if b == "zinc air":
        return "air"
    if b == "carbon zinc" and a in ("alkaline", "lithium", "silver oxide",
                                    "mercuric oxide"):
        return "carbon"
    return None


def voltage_gap(a, b):
    """Отклонение напряжения b от a — обёртка над двумя функциями выше и
    ЕДИНСТВЕННЫЙ способ получить его для пары записей."""
    r = signed_ratio(a.get("volts"), b.get("volts"))
    if r is None:
        return None
    return {"ratio": r, "pct": signed_pct(r), "class": consequence_class(r),
            "from": a["volts"], "to": b["volts"]}


def energy_mwh(cell):
    """Запас энергии в милливатт-часах: ёмкость на напряжение.

    Ёмкость сама по себе не сравнима между химиями — 150 мА·ч при 1,5 В и
    150 мА·ч при 3 В это вдвое разная энергия, а в источнике стоят два
    одинаковых числа.
    """
    if not cell.get("mah") or not cell.get("volts"):
        return None
    return cell["mah"] * cell["volts"]


def density_mwh_cc(cell):
    e = energy_mwh(cell)
    cc = cell.get("cc")
    if not e or not cc:
        return None
    return e / cc


def density_mwh_g(cell):
    e = energy_mwh(cell)
    g = cell.get("grams")
    if not e or not g:
        return None
    return e / g


def family(cell, cells):
    """Все элементы в той же оболочке, кроме самого. Это и есть ответ на
    вопрос «что подойдёт», ещё до разговора о напряжении."""
    s = shell(cell)
    if not s:
        return []
    return [c for c in cells
            if c["code"] != cell["code"] and shell(c) == s]


# ------------------------------------------ СТРОКА ТАБЛИЦЫ: ОДИН ПРЕДМЕТ
#
# ТРИ ДЕФЕКТА ОДНОГО РОДА В ОДНОЙ ТАБЛИЦЕ ЗА ТРИ ПРОВЕРКИ. Сначала процент
# считался от снятого, а стоял в ячейке рядом с напряжением снятого; потом
# рамка отсчёта была названа подписью неверно; потом вердикт посадки описывал
# элемент ЭТОЙ страницы, пока напряжение, химия и код той же строки описывали
# элемент СТРОКИ, — «sits lower» на 102 строках там, где предмет строки не
# садится ниже, а НЕ ДАЁТ ЗАКРЫТЬ КРЫШКУ. Каждый раз чинили СТОЛБЕЦ, а
# причина все три раза была одна: строка собиралась россыпью вызовов о двух
# аргументах, и то, о ком строка, держалось ПОРЯДКОМ этих аргументов, то есть
# нигде.
#
# ЗДЕСЬ ПРЕДМЕТ ОБЪЯВЛЕН. Пара — словарь с двумя ИМЕНОВАННЫМИ сторонами:
# frame — отсек, от которого ведётся отсчёт (элемент страницы), subject — тот,
# ПРО КОГО СТРОКА. Каждое вычисляемое поле получает ОДИН этот словарь и само
# называет сторону по имени; порядок аргументов больше не выражает ничего.
# Новый столбец заводится ТОЛЬКО записью в ROW_FIELDS и другой стороны не
# имеет: у поля, которое берёт pair["subject"], перепутать нечего, а поле,
# написанное мимо ROW_FIELDS, в строку не попадёт вовсе.


def _field_cell(pair):
    """Сама запись ПРЕДМЕТА: код, ссылка, химия, вытиснённое — всё, что
    печатается о строке, читается отсюда, а не из рамки."""
    return pair["subject"]


def _field_fit(pair):
    """Посадка ПРЕДМЕТА в отсек рамки: встанет ли он туда, где стоял тот.

    fits(a, b) отвечает «встанет ли b туда, где стоял a», и обе таблицы
    зовут её ОТСЮДА и в одну сторону. Пока таблица снятых звала её сама и
    наоборот, слово в ячейке было про элемент страницы, а три соседних
    столбца — про элемент строки.
    """
    return fits(pair["frame"], pair["subject"])


def _field_volt(pair):
    """Отклонение напряжения ПРЕДМЕТА от напряжения рамки."""
    return voltage_gap(pair["frame"], pair["subject"])


def _field_mah(pair):
    """Ёмкость ПРЕДМЕТА. Рамка в неё не входит вовсе — и это видно."""
    return pair["subject"].get("mah")


# Столбцы строки — ПОИМЁННО и в одном месте. Гейт «строка таблицы пары про
# один предмет» пересчитывает каждый из них из снимка и сверяет с
# напечатанным; столбец, заведённый мимо этого набора, в строке не появится.
ROW_FIELDS = (
    ("cell", _field_cell),
    ("fit", _field_fit),
    ("volt", _field_volt),
    ("mah", _field_mah),
)


def pair_row(frame, subject):
    """Строка таблицы пары: ВСЕ поля про ОДИН предмет, и предмет НАЗВАН.

    Единственный способ получить строку таблицы замен на этом сайте. Обе
    таблицы — «чем заменить» и «во что это можно поставить» — собираются ею и
    получают одну рамку: каждое поле описывает subject, отсчитанный от frame.
    Коды обеих сторон кладутся в строку отдельными полями, потому что
    подразумеваемый предмет — это ровно то, что тут ломалось трижды.
    """
    pair = {"frame": frame, "subject": subject}
    row = {"subject": subject["code"], "frame": frame["code"]}
    for name, fn in ROW_FIELDS:
        row[name] = fn(pair)
    return row


def replacements(cell, cells):
    """Чем заменить. Сначала посадка, потом близость напряжения, потом ёмкость.

    Порядок именно такой и он не произволен: то, что не влезает, бесполезно
    независимо от электрики; то, что влезает, но даёт не то напряжение, опасно
    независимо от ёмкости.

    ПРЕДМЕТ СТРОКИ — кандидат: строку целиком собирает pair_row, и отбор идёт
    по её же полю, а не по отдельному вызову рядом.
    """
    out = []
    coin = is_coin(cell)
    for c in cells:
        if c["code"] == cell["code"] or not c["active"]:
            continue
        # Тот же диаметр — ещё не тот же класс предмета. Без этой строки на
        # странице кнопки 15,5 x 6,1 мм в «почти подходит» попадал цилиндр
        # 15,6 x 27 мм: формально «тот же диаметр, выше», по сути другой
        # предмет. Сайт, предлагающий такое, выглядит не знающим своей темы.
        if is_coin(c) != coin:
            continue
        row = pair_row(cell, c)
        # «Выше» показываем НАРЯДУ с подходящими: «тот же диаметр, но крышка не
        # закроется» — это ответ, который читателю нужен не меньше, чем список
        # подходящих, и без него он попробует сам.
        if row["fit"] not in ("drop-in", "shorter", "taller"):
            continue
        out.append(row)
    # Ключ — НАПЕЧАТАННЫЙ процент, а не сырое отношение: MR44 и 303 на
    # странице PR44 печатают оба ±6.9%, и порядок между ними решался
    # двоичным хвостом 0.06896551724137923 < 0.06896551724137938. Порядок,
    # который со страницы не выводится, воспроизводимым не является;
    # последним ключом стоит код, чтобы у равных был ОДИН порядок.
    out.sort(key=lambda x: (FIT_ORDER[x["fit"]],
                            abs(x["volt"]["pct"]) if x["volt"] else 9,
                            -(x["mah"] or 0), x["cell"]["code"]))
    return out


def replaces(cell, cells):
    """Какие СНЯТЫЕ элементы этот выпускаемый заменяет.

    Обратная сторона цепочки замен. Человек ищет «чем заменить PX625» и
    попадает на страницу снятого; но человек, держащий в руках выпускаемый
    элемент, тоже хочет знать, во что его можно поставить. Первая версия знала
    только одно направление, и страница замены молчала о том, что она замена.

    РАМКА ТАКАЯ ЖЕ, КАК У replacements(), И ТЕПЕРЬ ЦЕЛИКОМ: отсчёт всегда от
    элемента ЭТОЙ страницы, а КАЖДОЕ поле строки — включая посадку — говорит
    про элемент СТРОКИ. Пока здесь стояло voltage_gap(c, cell), процент
    считался от снятого и стоял рядом с его же напряжением; пока стояло
    fits(c, cell), слово посадки говорило про элемент страницы в чужом отсеке,
    а соседние три столбца — про снятый. Столбец меняли дважды, мешала же
    россыпь вызовов: теперь строку целиком выдаёт pair_row, и другой стороны
    у неё нет.

    ОТБОР — ПО ПОЛЮ СТРОКИ. Берём снятые, которые в этот отсек садятся
    (drop-in) и которые ВЫШЕ него (taller): второе и есть прежнее «этот
    элемент сидит в старом отсеке ниже», сказанное про тот предмет, о котором
    вся остальная строка. Множество строк то же самое, слово — другое, и
    последствие у него противоположное: «ниже» значит «встанет и может
    потерять контакт», «выше» значит «крышка не закроется».
    """
    if not cell["active"]:
        return []
    coin = is_coin(cell)
    out = []
    for c in cells:
        if c["code"] == cell["code"] or c["active"]:
            continue
        if is_coin(c) != coin:
            continue
        row = pair_row(cell, c)
        if row["fit"] not in ("drop-in", "taller"):
            continue
        out.append(row)
    out.sort(key=lambda x: (FIT_ORDER[x["fit"]],
                            abs(x["volt"]["pct"]) if x["volt"] else 9,
                            x["cell"]["code"]))
    return out


def rank_in_shell(cells):
    """Место по запасу энергии среди элементов ОДНОЙ оболочки.

    Ранг считается ОДНОЙ функцией на весь сайт. Ранг, посчитанный в двух местах
    независимо, у нас уже расходился публично.
    """
    by_shell = {}
    for c in cells:
        s = shell(c)
        e = energy_mwh(c)
        if s and e:
            by_shell.setdefault(s, []).append((e, c["code"]))
    ranks = {}
    for s, rows in by_shell.items():
        rows.sort(key=lambda x: (-x[0], x[1]))
        place, prev, seen = 0, None, 0
        for e, code in rows:
            seen += 1
            if e != prev:
                place, prev = seen, e
            ranks[code] = (place, len(rows), e)
    return ranks


