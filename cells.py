def findable_codes(cell):
    """ВСЕ имена, по которым элемент обязан находиться, ОДНОЙ функцией.

    Указатель кодов и поиск главной собирали этот список каждый сам, и
    разойтись им было нечем помешать: на /codes/ оказалось 717 строк при 715
    обозначениях, а «15LF» вёл в два разных места.
    """
    out = [cell["code"]]
    for a in (cell.get("aliases") or []):
        if a not in out:
            out.append(a)
    rest = ([cell["iec_long"]] if cell.get("iec_long") else []) \
        + list(cell.get("px_forms") or []) \
        + [a for a, _ch in (cell.get("aliases_other_chem") or [])]
    for a in rest:
        if a not in out:
            out.append(a)
    return out


def code_depth_verdict(a, b):
    """Пишет ли стандарт РАЗНИЦУ ГЛУБИН этих двух элементов в их обозначения.

    «which the standard writes into the code» печаталось на 314 позициях и
    было верно на 30: у большинства соседей обозначение вообще не
    четырёхзначное, а у части кодируемая высота расходится с опубликованной.
    Три ответа, потому что случая три:
      "written" — оба кода четырёхзначные и высота в них совпадает с листом;
      "differs" — код есть, но кодируемая высота с листом не сходится;
      "absent"  — хотя бы у одного обозначение размера не кодирует вовсе.
    """
    seen = []
    for c in (a, b):
        ch = code_check(c)
        if ch is None:
            seen.append("absent")
        elif abs(ch["dh"]) < 0.05:
            seen.append("written")
        else:
            seen.append("differs")
    if "absent" in seen:
        return "absent"
    if "differs" in seen:
        return "differs"
    return "written"


def chem_envelope_overlap(cells_list, kind, others):
    """Сколько элементов химии `kind` стоят в оболочке, которую занимает и
    элемент одной из химий `others`. Возвращает (пересечение, всего).

    Утверждение о ПЕРЕСЕЧЕНИИ МНОЖЕСТВ — это величина. «Shares almost none of
    their holders» стояло в прозе про литий и не было посчитано ни разу: это
    дизъюнкция над множеством, которое никто не мерил.
    """
    by = {}
    for c in cells_list:
        s = shell(c)
        if s:
            by.setdefault(s, []).append(c)
    mine = [c for c in cells_list
            if chem_canon(c.get("chemistry")) == kind and shell(c)]
    share = [c for c in mine
             if any(chem_canon(o.get("chemistry")) in others
                    for o in by[shell(c)] if o["code"] != c["code"])]
    return len(share), len(mine)


def typical_volts_map(cells_list):
    """Характерное напряжение КАЖДОЙ химии, посчитанное по снимку.

    В шаблоне стояло набранное руками «1,35 V» для ртути, и оно спорило с
    собственными данными сайта на двенадцати страницах: 17 ртутных записей
    из 24 несут 1,4 В и ровно одна 1,35. Число в прозе печатается только из
    ПОСЧИТАННОЙ величины.
    """
    counts = {}
    for c in cells_list:
        k = chem_canon(c.get("chemistry"))
        v = c.get("volts")
        if not k or not v:
            continue
        counts.setdefault(k, {})
        counts[k][v] = counts[k].get(v, 0) + 1
    return {k: sorted(d.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
            for k, d in counts.items()}
